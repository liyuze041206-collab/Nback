import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {resolve} from 'node:path';
const origin=process.env.PORTAL_ORIGIN||'http://127.0.0.1:8000';
const folder=resolve(import.meta.dirname,'../../真实数据测试/网页上传数据/sub-01/ses-S1');
const browser=await chromium.launch({channel:'msedge',headless:true});
try{
  const page=await browser.newPage({viewport:{width:1440,height:1080}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(()=>localStorage.setItem('gspm.preferences.v1',JSON.stringify({theme:'dark',motion:true})));
  await page.goto(origin+'/portal.html#eeg');const eeg=page.frameLocator('#eeg-frame');
  await eeg.locator('#networkSvg').waitFor();
  assert.equal(await eeg.locator('#sourceSelect,#modelSelect,#support0File,#support2File').count(),0);
  assert(await eeg.locator('#startBtn').isDisabled());
  await eeg.locator('#queryFile').setInputFiles({name:'twoBACK.fdt',mimeType:'application/octet-stream',buffer:Buffer.from('x')});
  await eeg.locator('#uploadMessage').filter({hasText:'NPZ'}).waitFor();
  assert(await eeg.locator('#startBtn').isDisabled());
  const preparedResponse=page.waitForResponse(r=>r.url().endsWith('/prepare-analysis'));
  await eeg.locator('#queryFile').setInputFiles(resolve(folder,'sub-01_ses-S1_查询_2-back.npz'));
  const prepared=await(await preparedResponse).json();assert.equal(prepared.model_id,'sub-01');assert.equal(prepared.validation_subject,'sub-02');
  await eeg.locator('#matchStatus').filter({hasText:'sub-01 · ses-S1 · 已自动匹配'}).waitFor();
  const profile=await(await page.request.get(origin+'/api/calibrations')).json();
  assert.equal(profile.find(p=>p.id===prepared.calibration_id).shots,7);
  const response=page.waitForResponse(r=>r.url().endsWith('/api/analyses')&&r.request().method()==='POST');
  await eeg.locator('#startBtn').click();const job=await(await response).json();
  assert(await eeg.locator('.upload-button').isDisabled());
  // A real backend task continues while its view is hidden.
  await page.locator('.settings-trigger').click();await page.locator('[data-page=architecture]').click();
  let result;const deadline=Date.now()+60000;
  while(Date.now()<deadline){result=await(await page.request.get(origin+'/api/analyses/'+job.id)).json();if(['complete','failed'].includes(result.status))break;await page.waitForTimeout(150);}
  assert.equal(result.status,'complete',result.error);assert.equal(result.windows,137);
  await page.locator('.settings-trigger').click();await page.locator('[data-page=eeg]').click();
  await eeg.locator('#pct0').filter({hasText:'%'}).waitFor();
  assert.equal(await eeg.locator('#finalClass').innerText(),'2-back');
  assert.match(await eeg.locator('#finalVotes').innerText(),/共 137 个窗口/);
  assert.equal(await eeg.locator('#decisionSub').innerText(),'当前 2 秒窗口 · 时序概率');
  assert.equal(await eeg.locator('.sample-tag').innerText(),'250 Hz');
  assert.equal(await eeg.locator('#uploadMessage').isVisible(),false);
  await eeg.locator('#pulses circle').first().waitFor();await eeg.locator('#pauseBtn').click();
  await page.screenshot({path:resolve(import.meta.dirname,'../docs/real-upload-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.waitForTimeout(100);
  await page.screenshot({path:resolve(import.meta.dirname,'../docs/real-upload-mobile.png'),fullPage:true});
  assert(await eeg.locator('html').evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await eeg.locator('#resetBtn').click();
  assert.equal(await eeg.locator('#queryFile').evaluate(el=>el.files.length),1);
  assert.match(await eeg.locator('#matchStatus').innerText(),/已自动匹配/);
  assert(await eeg.locator('#startBtn').isEnabled());
  assert.equal(await eeg.locator('#pulses circle').count(),0);
  assert.deepEqual(errors,[]);
  console.log(JSON.stringify({passed:true,real_windows:result.windows,checks:['single query upload','automatic held-out fold','seven-shot support','real inference while hidden','desktop/mobile','Reset retains match']}));
}finally{await browser.close();}
